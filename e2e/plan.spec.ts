import { expect, test, type Page } from "@playwright/test";
import { airFixture } from "./fixture";
import { deterministicPlan } from "../lib/plan-fallback";
import { deterministicIndoorPlan } from "../lib/indoor-guidance";

async function mockAir(page: Page) {
  await page.route("**/api/air*", (route) =>
    route.fulfill({
      status: 200,
      contentType: "application/json",
      body: JSON.stringify(airFixture()),
    }),
  );
}

test.describe("Daily Plan", () => {
  test("discloses and renders rule-based actions when both models are unavailable", async ({ page }) => {
    await mockAir(page);
    await page.route("**/api/ai", (route) =>
      route.fulfill({
        status: 200,
        contentType: "application/json",
        body: JSON.stringify({
          mode: "plan",
          data: deterministicPlan(airFixture(), {}),
          model: "deterministic",
          configured: true,
          fallback: "deterministic",
        }),
      }),
    );

    await page.goto("/plan");
    await page.getByRole("button", { name: "Build today's plan" }).click();

    await expect(
      page.getByText(/Both AI models were temporarily unavailable/),
    ).toBeVisible();
    await expect(page.getByText(/deterministic decision engine/).first()).toBeVisible();
    await expect(page.getByText("Generated by deterministic")).toBeVisible();
    const items = page.locator("ol > li");
    await expect(items).toHaveCount(5);
  });

  test("indoor guidance discloses rule-based fallback", async ({ page }) => {
    await mockAir(page);
    await page.route("**/api/ai", (route) =>
      route.fulfill({
        status: 200,
        contentType: "application/json",
        body: JSON.stringify({
          mode: "indoor",
          data: deterministicIndoorPlan(airFixture()),
          model: "deterministic",
          configured: true,
          fallback: "deterministic",
        }),
      }),
    );

    await page.goto("/indoor");
    await page.getByRole("button", { name: "Get indoor advice" }).click();
    await expect(page.getByText(/This guidance came from the deterministic indoor rules/)).toBeVisible();
    await expect(page.locator("ol > li")).toHaveCount(5);
  });

  test("decision explanation discloses rule-based fallback", async ({ page }) => {
    await mockAir(page);
    await page.route("**/api/ai", (route) =>
      route.fulfill({
        status: 200,
        contentType: "application/json",
        body: JSON.stringify({
          mode: "explain",
          decisionId: "outdoor",
          data: {
            headline: "Move plans indoors",
            why: "CPCB AQI 284 sits in the Poor band.",
            whatToDo: "Move plans indoors.",
            uncertainty: "Indoor air is not measured.",
          },
          model: "deterministic",
          configured: true,
          fallback: "deterministic",
        }),
      }),
    );

    await page.goto("/decisions");
    await page.getByRole("button", { name: "Explain with AI" }).first().click();
    await expect(page.getByText(/This explanation is the rule and evidence/)).toBeVisible();
    await expect(page.getByText(/AI explanation by deterministic/)).toBeVisible();
  });
});
